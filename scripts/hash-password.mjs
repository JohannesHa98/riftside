/**
 * Prints the ADMIN_PASSWORD_HASH value for a password you type.
 *
 * Run it in your own terminal:  npm run auth:hash
 *
 * The password is never echoed, never written to a file, and never stored
 * anywhere by this script — only the hash is printed. Imports the same module
 * the app verifies with, so the two cannot drift apart.
 */
import { createInterface } from "node:readline";

import { hashPassword } from "../lib/password.ts";

const password = await readPassword("Password (not shown as you type): ");

if (password.length === 0) {
  console.error("\nNo password given. Nothing to hash.");
  process.exit(1);
}

if (password.length < 12) {
  console.error(
    `\nThat password is ${password.length} characters. Use at least 12 — ideally one generated by a password manager.`,
  );
  process.exit(1);
}

console.log("\nAdd this to .env.local and to the Vercel project settings:\n");
console.log(`ADMIN_PASSWORD_HASH=${await hashPassword(password)}\n`);

function readPassword(prompt) {
  // Piped input (echo 'pw' | npm run auth:hash) has no terminal to mute.
  if (!process.stdin.isTTY) {
    return new Promise((resolve) => {
      let input = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (chunk) => (input += chunk));
      process.stdin.on("end", () => resolve(input.trim()));
    });
  }

  return new Promise((resolve) => {
    process.stdout.write(prompt);

    const rl = createInterface({
      input: process.stdin,
      output: process.stdout,
      terminal: true,
    });

    // Write the prompt ourselves above, then swallow every echo after it.
    rl._writeToOutput = () => {};

    rl.question("", (answer) => {
      rl.close();
      process.stdout.write("\n");
      resolve(answer.trim());
    });
  });
}
